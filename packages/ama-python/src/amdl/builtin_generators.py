class BlueprintGenerator(Generator):
    name = "blueprint"

    def generate(self, context: GenerationContext) -> Iterable[GeneratedArtifact]:
        doc = context.document
        index_lines = [
            HEADER,
            f"# {doc.metadata.name} — Enterprise Blueprint\n",
            f"> Version {doc.metadata.version} · AMDL {doc.amdl}\n",
            doc.metadata.description + "\n",
            "## Domains\n",
        ]
        for domain in doc.domains:
            index_lines.append(
                f"- [{domain.name}](domains/{kebab(domain.id)}.md) — {domain.description}"
            )
        index_path = context.output_dir / "blueprint" / "README.md"
        write_text(index_path, "\n".join(index_lines) + "\n")
        yield GeneratedArtifact(str(index_path.relative_to(context.output_dir)), "blueprint")

        for domain in doc.domains:
            lines = [
                HEADER,
                f"# Domain Blueprint — {domain.name}\n",
                domain.description + "\n",
                f"**Owner:** {domain.owner or 'Unassigned'}  ",
                f"**Dependencies:** {', '.join(domain.depends_on) or 'None'}\n",
            ]
            sections: list[tuple[str, list[Any]]] = [
                ("Capabilities", domain.capabilities),
                ("Entities", domain.entities),
                ("Value Objects", domain.value_objects),
                ("Use Cases", domain.use_cases),
                ("Events", domain.events),
                ("Policies", domain.policies),
                ("Workflows", domain.workflows),
                ("Agents", domain.agents),
                ("Tools", domain.tools),
                ("Integrations", domain.integrations),
                ("API Resources", domain.api_resources),
                ("UI Surfaces", domain.ui_surfaces),
                ("Metrics", domain.metrics),
                ("Permissions", domain.permissions),
                ("Roles", domain.roles),
                ("Feature Flags", domain.feature_flags),
                ("Deployment Targets", domain.deployment_targets),
                ("Evaluations", domain.evaluations),
                ("Test Specs", domain.test_specs),
            ]
            for title, items in sections:
                lines.append(f"## {title}\n")
                if not items:
                    lines.append("_None declared._\n")
                    continue
                for item in items:
                    lines.append(f"### {item.name} (`{item.id}`)\n")
                    description = getattr(item, "description", "")
                    if description:
                        lines.append(description + "\n")
                    payload = item.model_dump(
                        mode="json", exclude={"id", "name", "description"}, exclude_none=True
                    )
                    if payload:
                        lines.append("```yaml")
                        lines.append(
                            yaml.safe_dump(payload, sort_keys=False, allow_unicode=True).rstrip()
                        )
                        lines.append("```\n")
            path = context.output_dir / "blueprint" / "domains" / f"{kebab(domain.id)}.md"
            write_text(path, "\n".join(lines) + "\n")
            source_ids = tuple(f"domain:{domain.id}.{x.id}" for x in domain.entities)
            yield GeneratedArtifact(
                str(path.relative_to(context.output_dir)), "blueprint", source_ids
            )


class SchemaGenerator(Generator):
    name = "schema"

    def generate(self, context: GenerationContext) -> Iterable[GeneratedArtifact]:
        lines = [
            "-- Generated by AMA/AMDL. Review before applying.",
            "-- Non-destructive baseline: CREATE TABLE/INDEX/POLICY only.",
            "begin;",
            "create extension if not exists pgcrypto;",
            "create extension if not exists vector;",
            "",
        ]
        for domain in context.document.domains:
            lines.append(f"-- Domain: {domain.name}")
            for entity in domain.entities:
                workspace, audited, versioned, soft_delete = _entity_flags(context, entity)
                table = _table(entity)
                columns = ["  id uuid primary key default gen_random_uuid()"]
                if workspace:
                    columns.append(
                        "  workspace_id uuid not null references public.workspaces(id) on delete cascade"
                    )
                for field in entity.fields:
                    col = f"  {snake(field.name)} {_sql_type(field)}"
                    if field.required:
                        col += " not null"
                    if field.unique:
                        col += " unique"
                    if field.default is not None:
                        if isinstance(field.default, bool):
                            default = "true" if field.default else "false"
                        elif isinstance(field.default, (int, float)):
                            default = str(field.default)
                        else:
                            default = "'" + str(field.default).replace("'", "''") + "'"
                        col += f" default {default}"
                    if field.type.kind == "enum" and field.type.values:
                        values = ", ".join(
                            "'" + value.replace("'", "''") + "'" for value in field.type.values
                        )
                        col += f" check ({snake(field.name)} in ({values}))"
                    if field.type.kind == "reference" and field.type.target:
                        target = context.registry.resolve(field.type.target, {"entity"})
                        if target:
                            target_table = _table(target.value)
                            col += f" references public.{target_table}(id)"
                    columns.append(col)
                if entity.states and not any(f.name == "status" for f in entity.fields):
                    values = ", ".join(f"'{state}'" for state in entity.states)
                    columns.append(
                        f"  status text not null default '{entity.states[0]}' check (status in ({values}))"
                    )
                columns.extend(
                    [
                        "  version integer not null default 1",
                        "  metadata jsonb not null default '{}'::jsonb",
                        "  created_at timestamptz not null default now()",
                        "  updated_at timestamptz not null default now()",
                    ]
                )
                if audited:
                    columns.extend(
                        [
                            "  created_by uuid references auth.users(id)",
                            "  updated_by uuid references auth.users(id)",
                            "  created_by_agent_id uuid",
                            "  correlation_id uuid",
                        ]
                    )
                if soft_delete:
                    columns.append("  deleted_at timestamptz")
                lines.append(
                    f"create table if not exists public.{table} (\n" + ",\n".join(columns) + "\n);"
                )
                for field in entity.fields:
                    if field.indexed:
                        lines.append(
                            f"create index if not exists idx_{table}_{snake(field.name)} on public.{table} ({snake(field.name)});"
                        )
                for index in entity.indexes:
                    unique = "unique " if index.unique else ""
                    fields = ", ".join(snake(f) for f in index.fields)
                    lines.append(
                        f"create {unique}index if not exists {snake(index.name)} on public.{table} using {index.method} ({fields});"
                    )
                if workspace:
                    lines.extend(
                        [
                            f"alter table public.{table} enable row level security;",
                            f'drop policy if exists "workspace members read {table}" on public.{table};',
                            f'create policy "workspace members read {table}" on public.{table} for select using (public.is_workspace_member(workspace_id));',
                            f'drop policy if exists "workspace editors write {table}" on public.{table};',
                            f"create policy \"workspace editors write {table}\" on public.{table} for all using (public.has_workspace_role(workspace_id, array['owner','admin','editor'])) with check (public.has_workspace_role(workspace_id, array['owner','admin','editor']));",
                        ]
                    )
                if versioned:
                    version_table = f"{table}_versions"
                    lines.append(
                        f"create table if not exists public.{version_table} ("
                        "id uuid primary key default gen_random_uuid(), "
                        f"{snake(entity.id)}_id uuid not null references public.{table}(id) on delete cascade, "
                        "version integer not null, snapshot jsonb not null, change_reason text, "
                        "created_at timestamptz not null default now(), created_by uuid references auth.users(id), "
                        f"unique ({snake(entity.id)}_id, version));"
                    )
                lines.append("")
        lines.extend(["commit;", ""])
        path = context.output_dir / "schema" / "supabase-migration.sql"
        write_text(path, "\n".join(lines))
        yield GeneratedArtifact(str(path.relative_to(context.output_dir)), "sql")


class OpenAPIGenerator(Generator):
    name = "openapi"

    def generate(self, context: GenerationContext) -> Iterable[GeneratedArtifact]:
        paths: dict[str, Any] = {}
        schemas: dict[str, Any] = {}
        for domain in context.document.domains:
            for entity in domain.entities:
                schema_name = entity.name.replace(" ", "")
                properties: dict[str, Any] = {"id": {"type": "string", "format": "uuid"}}
                required: list[str] = []
                for field in entity.fields:
                    properties[field.name] = self._field_schema(field.type)
                    if field.description:
                        properties[field.name]["description"] = field.description
                    if field.required:
                        required.append(field.name)
                schemas[schema_name] = {
                    "type": "object",
                    "properties": properties,
                    "required": required,
                }
            for resource in domain.api_resources:
                entity_entry = (
                    context.registry.resolve(resource.entity, {"entity"})
                    if resource.entity
                    else None
                )
                schema_name = (
                    entity_entry.value.name.replace(" ", "") if entity_entry else "CommandResult"
                )
                base = f"/api/{resource.version}{resource.path}"
                if "list" in resource.operations:
                    paths.setdefault(base, {})["get"] = self._operation(
                        resource, "list", schema_name
                    )
                if "create" in resource.operations or "execute" in resource.operations:
                    paths.setdefault(base, {})["post"] = self._operation(
                        resource, "create", schema_name
                    )
                detail = base + "/{id}"
                if "get" in resource.operations:
                    paths.setdefault(detail, {})["get"] = self._operation(
                        resource, "get", schema_name
                    )
                if "update" in resource.operations:
                    paths.setdefault(detail, {})["patch"] = self._operation(
                        resource, "update", schema_name
                    )
                if "archive" in resource.operations:
                    paths.setdefault(detail, {})["delete"] = self._operation(
                        resource, "archive", schema_name
                    )
        spec = {
            "openapi": "3.1.0",
            "info": {
                "title": context.document.metadata.name,
                "version": context.document.metadata.version,
                "description": context.document.metadata.description,
            },
            "servers": [{"url": "https://api.example.com"}],
            "security": [{"bearerAuth": []}],
            "paths": paths,
            "components": {
                "securitySchemes": {
                    "bearerAuth": {"type": "http", "scheme": "bearer", "bearerFormat": "JWT"}
                },
                "schemas": schemas,
            },
        }
        path = context.output_dir / "api" / "openapi.json"
        write_json(path, spec)
        yield GeneratedArtifact(str(path.relative_to(context.output_dir)), "openapi")

    @staticmethod
    def _field_schema(type_spec: TypeSpec) -> dict[str, Any]:
        return _field_json_schema(type_spec)

    @staticmethod
    def _operation(resource, action: str, schema_name: str) -> dict[str, Any]:
        operation = {
            "operationId": f"{action}_{resource.id}".replace("-", "_"),
            "summary": f"{action.title()} {resource.name}",
            "tags": [resource.id],
            "responses": {"200": {"description": "Successful operation"}},
            "x-amdl-resource": resource.id,
        }
        if action in {"create", "update"}:
            operation["requestBody"] = {
                "required": True,
                "content": {
                    "application/json": {"schema": {"$ref": f"#/components/schemas/{schema_name}"}}
                },
            }
        if action in {"get", "update", "archive"}:
            operation["parameters"] = [
                {
                    "name": "id",
                    "in": "path",
                    "required": True,
                    "schema": {"type": "string", "format": "uuid"},
                }
            ]
        return operation


class TypeScriptGenerator(Generator):
    name = "typescript"

    def generate(self, context: GenerationContext) -> Iterable[GeneratedArtifact]:
        lines = ["// Generated by AMA/AMDL. Do not edit directly.", ""]
        event_names: list[str] = []
        for domain in context.document.domains:
            lines.append(f"// Domain: {domain.name}")
            for entity in domain.entities:
                lines.append(f"export interface {entity.name.replace(' ', '')} {{")
                lines.append("  id: string;")
                workspace, audited, _, soft_delete = _entity_flags(context, entity)
                if workspace:
                    lines.append("  workspaceId: string;")
                for field in entity.fields:
                    optional = "" if field.required else "?"
                    lines.append(f"  {field.name}{optional}: {_type_name(field)};")
                if entity.states and not any(field.name == "status" for field in entity.fields):
                    lines.append(
                        "  status: " + " | ".join(json.dumps(x) for x in entity.states) + ";"
                    )
                lines.extend(
                    [
                        "  version: number;",
                        "  metadata: Record<string, unknown>;",
                        "  createdAt: string;",
                        "  updatedAt: string;",
                    ]
                )
                if audited:
                    lines.extend(
                        [
                            "  createdBy?: string;",
                            "  updatedBy?: string;",
                            "  createdByAgentId?: string;",
                        ]
                    )
                if soft_delete:
                    lines.append("  deletedAt?: string;")
                lines.append("}\n")
            for event in domain.events:
                event_names.append(event.id)
                type_name = "".join(part.title() for part in event.id.split("-"))
                lines.append(f"export interface {type_name}Event {{")
                lines.append(f"  type: {json.dumps(event.id)};")
                lines.append("  eventId: string;")
                lines.append("  workspaceId: string;")
                lines.append("  occurredAt: string;")
                lines.append("  correlationId: string;")
                lines.append("  payload: {")
                for field in event.payload:
                    optional = "" if field.required else "?"
                    lines.append(f"    {field.name}{optional}: {_type_name(field)};")
                lines.append("  };\n}\n")
        if event_names:
            types = [
                "".join(part.title() for part in name.split("-")) + "Event" for name in event_names
            ]
            lines.append("export type DomainEvent = " + " | ".join(types) + ";\n")
        path = context.output_dir / "contracts" / "domain.ts"
        write_text(path, "\n".join(lines))
        yield GeneratedArtifact(str(path.relative_to(context.output_dir)), "typescript")


