HEADER = "<!-- Generated by AMA/AMDL. Edit the AMDL source, not this artifact. -->\n\n"


def _type_name(field: FieldSpec) -> str:
    kind = field.type.kind
    if kind in {"string", "text", "url", "email", "uuid", "date", "datetime", "money"}:
        return "string"
    if kind in {"integer", "number"}:
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "json":
        return "Record<string, unknown>"
    if kind == "array":
        return f"{field.type.items or 'unknown'}[]"
    if kind == "enum":
        return " | ".join(json.dumps(v) for v in field.type.values)
    if kind == "reference":
        return "string"
    if kind == "vector":
        return "number[]"
    return "unknown"


def _sql_type(field: FieldSpec) -> str:
    kind = field.type.kind
    return {
        "string": "text",
        "text": "text",
        "integer": "integer",
        "number": "numeric",
        "boolean": "boolean",
        "uuid": "uuid",
        "date": "date",
        "datetime": "timestamptz",
        "money": "numeric(14,2)",
        "url": "text",
        "email": "text",
        "json": "jsonb",
        "array": "jsonb",
        "enum": "text",
        "reference": "uuid",
        "vector": f"vector({field.type.dimensions or 1536})",
    }[kind]


def _table(entity: EntitySpec) -> str:
    return entity.table or plural(snake(entity.id))


def _entity_flags(context: GenerationContext, entity: EntitySpec) -> tuple[bool, bool, bool, bool]:
    defaults = context.document.defaults
    workspace = (
        defaults.workspace_scoped if entity.workspace_scoped is None else entity.workspace_scoped
    )
    audited = defaults.audited if entity.audited is None else entity.audited
    versioned = defaults.versioned if entity.versioned is None else entity.versioned
    soft_delete = defaults.soft_delete if entity.soft_delete is None else entity.soft_delete
    return workspace, audited, versioned, soft_delete


def _field_json_schema(type_spec: TypeSpec) -> dict[str, Any]:
    """Map an AMDL ``TypeSpec`` to a JSON Schema / OpenAPI schema fragment."""
    kind = type_spec.kind
    if kind in {"integer"}:
        return {"type": "integer"}
    if kind in {"number", "money"}:
        return {"type": "number"}
    if kind == "boolean":
        return {"type": "boolean"}
    if kind in {"json"}:
        return {"type": "object", "additionalProperties": True}
    if kind in {"array", "vector"}:
        return {"type": "array", "items": {"type": "number" if kind == "vector" else "string"}}
    schema: dict[str, Any] = {"type": "string"}
    if kind in {"uuid", "reference"}:
        schema["format"] = "uuid"
    elif kind == "date":
        schema["format"] = "date"
    elif kind == "datetime":
        schema["format"] = "date-time"
    elif kind == "url":
        schema["format"] = "uri"
    elif kind == "email":
        schema["format"] = "email"
    elif kind == "enum":
        schema["enum"] = type_spec.values
    return schema


