class ComponentManifestGenerator(Generator):
    name = "components"

    def generate(self, context: GenerationContext) -> Iterable[GeneratedArtifact]:
        usage: dict[str, list[str]] = {}
        for domain in context.document.domains:
            for surface in domain.ui_surfaces:
                for component in surface.components:
                    usage.setdefault(component, []).append(f"ui_surface:{domain.id}.{surface.id}")
        components = [
            {"component": name, "used_by": sorted(surfaces)}
            for name, surfaces in sorted(usage.items())
        ]
        path = context.output_dir / "ui" / "component-manifest.json"
        write_json(path, {"version": "1.0", "components": components})
        yield GeneratedArtifact(str(path.relative_to(context.output_dir)), "component-manifest")


class GovernanceReportGenerator(Generator):
    """Scan generated artifacts for destructive or unsafe operations (ETAPA 8)."""

    name = "governance"

    def generate(self, context: GenerationContext) -> Iterable[GeneratedArtifact]:
        findings = []
        sql_path = context.output_dir / "schema" / "supabase-migration.sql"
        if sql_path.exists():
            sql = sql_path.read_text(encoding="utf-8")
            findings.extend(scan_sql(sql))
            findings.extend(scan_secrets(sql, location="schema/supabase-migration.sql"))
        findings.extend(scan_secrets(json.dumps(context.registry.to_dict()), location="registry"))

        sensitive_fields = sorted(
            f"{domain.id}.{entity.id}.{field.name}"
            for domain in context.document.domains
            for entity in domain.entities
            for field in entity.fields
            if field.sensitive
        )
        non_isolated = sorted(
            f"{domain.id}.{entity.id}"
            for domain in context.document.domains
            for entity in domain.entities
            if (
                context.document.defaults.workspace_scoped
                if entity.workspace_scoped is None
                else entity.workspace_scoped
            )
            is False
            and entity.ownership != "system"
        )
        agent_boundaries = [
            {
                "agent": f"agent:{domain.id}.{agent.id}",
                "approval_boundary": agent.approval_boundary,
                "external_write_tools": [
                    t.id for t in domain.tools if t.id in agent.tools and t.external_writes
                ],
            }
            for domain in context.document.domains
            for agent in domain.agents
        ]
        report = {
            "version": "1.0",
            "overall_risk": highest_risk(findings),
            "destructive_operations": [f.to_dict() for f in findings],
            "requires_human_approval": any(f.requires_approval for f in findings),
            "migration_strategy": "additive-only (CREATE ... IF NOT EXISTS)",
            "sensitive_fields": sensitive_fields,
            "non_workspace_isolated_entities": non_isolated,
            "agent_approval_boundaries": agent_boundaries,
        }
        json_path = context.output_dir / "governance" / "governance-report.json"
        write_json(json_path, report)
        lines = [
            HEADER,
            "# Governance & Safety Report\n",
            f"- Overall risk: **{report['overall_risk']}**",
            f"- Destructive operations detected: **{len(findings)}**",
            f"- Requires explicit human approval: **{report['requires_human_approval']}**",
            f"- Migration strategy: `{report['migration_strategy']}`",
            f"- Sensitive fields tracked: **{len(sensitive_fields)}**",
            "",
            "This report is derived from the AMDL specification. The generated SQL is "
            "additive by construction; any destructive change (DROP, TRUNCATE, disabling "
            "RLS, unrestricted policies) is flagged here and must be approved by a human "
            "before it is applied. No SQL is applied automatically.",
            "",
        ]
        if findings:
            lines.extend(
                [
                    "## Flagged operations",
                    "",
                    "| Code | Risk | Location | Message |",
                    "| --- | --- | --- | --- |",
                ]
            )
            lines.extend(f"| {f.code} | {f.risk} | {f.location} | {f.message} |" for f in findings)
            lines.append("")
        else:
            lines.append("> No destructive operations or embedded secrets were detected.\n")
        md_path = context.output_dir / "governance" / "governance-report.md"
        write_text(md_path, "\n".join(lines))
        yield GeneratedArtifact(str(json_path.relative_to(context.output_dir)), "governance")
        yield GeneratedArtifact(str(md_path.relative_to(context.output_dir)), "governance")


